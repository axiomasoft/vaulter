ITEM_IN_SECTION = re.compile(r"(?:^| / )(P\d+\.\d+) —")
FAZA_ONLY = re.compile(r"^F\d — ")
PUNKT = re.compile(r"P\d+\.\d+|P\d+\.x")


def scenario_owners(rows: list[dict]) -> str:
    owners: set[str] = set()
    for r in rows:
        if r["kind"] != "row":
            continue
        last = [c.strip() for c in r["text"].strip("|").split("|")][-1]
        for token in PUNKT.findall(last):
            if token == "P2.x":
                owners.update({"P2.1"})
            else:
                owners.add(token)
    return ",".join(sorted(owners, key=lambda o: [int(x) for x in o[1:].split(".")]))


def main() -> int:
    with UNITS.open(encoding="utf-8", newline="") as fh:
        units = list(csv.DictReader(fh, delimiter="\t"))
    sections: dict[tuple[str, str], list[dict]] = {}
    for u in units:
        sections.setdefault((u["file"], u["section"]), []).append(u)
    out: list[tuple[str, str, str]] = []
    missing: list[str] = []
    for (file, section), rows in sections.items():
        prefix = file[:2]
        owners = None
        if prefix == "13":
            m = ITEM_IN_SECTION.search(section)
            if m:
                owners = m.group(1)
            elif FAZA_ONLY.match(section) and rows[0]["kind"] == "heading":
                owners = "plan:D03"
        if prefix == "14" and section != "(preamble)" and not section.startswith("Покрытие"):
            owners = scenario_owners(rows)
        if prefix == "14" and section == "(preamble)":
            owners = "plan:D01"
        if prefix == "14" and section.startswith("Покрытие"):
            owners = "P8.1"
        if owners is None:
            for rp, needle, own in RULES:
                if rp == prefix and (needle == "*" or needle in section):
                    owners = own
                    break
        if not owners:
            missing.append(f"{file} :: {section}")
            continue
        out.append((file, section, owners))
    if missing:
        print("секции без правила владельца:", *missing, sep="\n  ")
        return 1
    with OUT.open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, delimiter="\t", lineterminator="\n")
        w.writerow(["file", "section", "owners"])
        w.writerows(out)
    print(f"section-owners: {len(out)} секций")
    return 0


if __name__ == "__main__":
    sys.exit(main())
